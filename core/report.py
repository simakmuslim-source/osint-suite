"""
OSINT Report generator
Produces Markdown, JSON and optional PDF.
"""

from __future__ import annotations
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional
import json


def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def build_report(
    username_data: Optional[Dict] = None,
    phone_data: Optional[Dict] = None,
    contacts_data: Optional[Dict] = None,
    image_data: Optional[Dict] = None,
    extra_notes: Optional[List[str]] = None,
) -> Dict[str, Any]:
    """Collect all sections into one structured dict."""
    return {
        "generated_at": _now(),
        "tool": "osint-suite",
        "username": username_data,
        "phone": phone_data,
        "contacts": contacts_data,
        "image": image_data,
        "notes": extra_notes or [],
    }


def to_markdown(data: Dict[str, Any]) -> str:
    lines: List[str] = [
        "# OSINT Report",
        "",
        f"**Generated:** {data.get('generated_at', _now())}  ",
        f"**Tool:** {data.get('tool', 'osint-suite')}",
        "",
        "---",
        "",
    ]

    u = data.get("username")
    if u:
        lines.append(f"## Username: `{u.get('query')}`")
        lines.append("")
        found = u.get("found") or []
        lines.append(f"Found on **{len(found)}** sites (checked ~{u.get('total_checked', '?')}).")
        lines.append("")
        if found:
            for r in found:
                site = r.get("site", "?")
                url = r.get("url", "")
                lines.append(f"- [{site}]({url})")
        else:
            lines.append("_No public profiles found._")
        lines.append("")

    p = data.get("phone")
    if p:
        lookup = p.get("lookup") or {}
        vk = p.get("vk") or {}
        lines.append(f"## Phone: `{lookup.get('input') or lookup.get('normalized')}`")
        lines.append("")
        lines.append(f"- **Normalized:** `{lookup.get('normalized')}`")
        lines.append(f"- **Operator:** {lookup.get('operator')}")
        lines.append(f"- **Region:** {lookup.get('region')}")
        lines.append(f"- **Country:** {lookup.get('country')}")
        lines.append("")
        if vk.get("notes"):
            lines.append("### VK notes")
            for n in vk["notes"]:
                lines.append(f"- {n}")
            lines.append("")

    c = data.get("contacts")
    if c:
        lines.append("## Contacts from page")
        lines.append("")
        lines.append(f"**URL:** {c.get('url')}")
        if c.get("error"):
            lines.append(f"**Error:** {c['error']}")
        else:
            emails = c.get("emails") or []
            phones = c.get("phones") or []
            social = c.get("social") or {}
            lines.append(f"- Emails ({len(emails)}): " + (", ".join(f'`{e}`' for e in emails) or "—"))
            lines.append(f"- Phones ({len(phones)}): " + (", ".join(f'`{p}`' for p in phones) or "—"))
            if social:
                lines.append("- Social:")
                for net, urls in social.items():
                    for u in urls:
                        lines.append(f"  - {net}: {u}")
        lines.append("")

    img = data.get("image")
    if img:
        lines.append("## Image")
        lines.append("")
        lines.append(f"- Path: `{img.get('path')}`")
        if img.get("matches") is not None:
            lines.append(f"- Local similar images found: **{len(img['matches'])}**")
        lines.append("")

    notes = data.get("notes") or []
    if notes:
        lines.append("## Notes")
        lines.append("")
        for n in notes:
            lines.append(f"- {n}")
        lines.append("")

    lines.append("---")
    lines.append("_Report generated by osint-suite (free, local)._")
    return "\n".join(lines)


def to_pdf(data: Dict[str, Any], pdf_path: str) -> str:
    """Write a simple PDF report using fpdf2."""
    try:
        from fpdf import FPDF
    except ImportError as e:
        raise ImportError("fpdf2 is required for PDF export: pip install fpdf2") from e

    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 10, "OSINT Report", ln=True)
    pdf.set_font("Helvetica", size=10)
    pdf.cell(0, 6, f"Generated: {data.get('generated_at', _now())}", ln=True)
    pdf.cell(0, 6, "Tool: osint-suite", ln=True)
    pdf.ln(4)

    def section(title: str):
        pdf.set_font("Helvetica", "B", 12)
        pdf.cell(0, 8, title, ln=True)
        pdf.set_font("Helvetica", size=10)

    def line(text: str):
        # FPDF core fonts are latin-1; strip/replace non-ascii safely
        safe = text.encode("latin-1", errors="replace").decode("latin-1")
        pdf.multi_cell(0, 5, safe)

    u = data.get("username")
    if u:
        section(f"Username: {u.get('query')}")
        found = u.get("found") or []
        line(f"Found on {len(found)} sites (checked ~{u.get('total_checked', '?')}).")
        for r in found[:50]:
            line(f"- {r.get('site')}: {r.get('url')}")
        pdf.ln(2)

    p = data.get("phone")
    if p:
        lookup = p.get("lookup") or {}
        section(f"Phone: {lookup.get('input') or lookup.get('normalized')}")
        line(f"Normalized: {lookup.get('normalized')}")
        line(f"Operator: {lookup.get('operator')}")
        line(f"Region: {lookup.get('region')}")
        line(f"Country: {lookup.get('country')}")
        pdf.ln(2)

    c = data.get("contacts")
    if c:
        section("Contacts from page")
        line(f"URL: {c.get('url')}")
        if c.get("error"):
            line(f"Error: {c['error']}")
        else:
            line("Emails: " + ", ".join(c.get("emails") or []) or "—")
            line("Phones: " + ", ".join(c.get("phones") or []) or "—")
        pdf.ln(2)

    img = data.get("image")
    if img:
        section("Image")
        line(f"Path: {img.get('path')}")
        pdf.ln(2)

    notes = data.get("notes") or []
    if notes:
        section("Notes")
        for n in notes:
            line(f"- {n}")

    pdf.ln(4)
    line("Generated by osint-suite (free, local).")
    pdf.output(pdf_path)
    return pdf_path


def save_report(
    data: Dict[str, Any],
    md_path: str = "report.md",
    json_path: Optional[str] = None,
    pdf_path: Optional[str] = None,
) -> Dict[str, str]:
    """Write Markdown, optional JSON and optional PDF."""
    md = to_markdown(data)
    Path(md_path).write_text(md, encoding="utf-8")
    written = {"markdown": md_path}

    if json_path:
        Path(json_path).write_text(
            json.dumps(data, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
        written["json"] = json_path

    if pdf_path:
        to_pdf(data, pdf_path)
        written["pdf"] = pdf_path

    return written
